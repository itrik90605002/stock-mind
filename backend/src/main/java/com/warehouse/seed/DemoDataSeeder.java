/**
 * Loads demo data on first start when {@code app.demo.seed-data=true} and the database has no
 * users. Never touches a populated database.
 *
 * <p>Master data (4 warehouses, 10 suppliers, 120 products, 7 users) comes from the JSON files in
 * {@code resources/seed/}; 90 days of operating history are generated by {@link HistorySimulator}
 * and bulk-inserted with JDBC batches. Demo logins:
 *
 * <pre>
 *   admin@warehouse.local          / Admin@12345   (all warehouses)
 *   manager@warehouse.local        / Manager@123   (PUN-01, MUM-02)
 *   north.manager@warehouse.local  / Manager@123   (DEL-03, BLR-04)
 *   clerk@warehouse.local          / Clerk@1234    (PUN-01)
 * </pre>
 */
@Component
@Order(1)
public class DemoDataSeeder implements ApplicationRunner {

    private static final Logger log = LoggerFactory.getLogger(DemoDataSeeder.class);
    private static final int BATCH = 1000;

    private final AppProperties properties;
    private final UserRepository userRepository;
    private final WarehouseRepository warehouseRepository;
    private final SupplierRepository supplierRepository;
    private final ProductRepository productRepository;
    private final PasswordEncoder passwordEncoder;
    private final JdbcTemplate jdbc;
    private final ObjectMapper objectMapper;
    private final Clock clock;

    public DemoDataSeeder(AppProperties properties, UserRepository userRepository,
                          WarehouseRepository warehouseRepository, SupplierRepository supplierRepository,
                          ProductRepository productRepository, PasswordEncoder passwordEncoder, JdbcTemplate jdbc,
                          ObjectMapper objectMapper, Clock clock) {
        this.properties = properties;
        this.userRepository = userRepository;
        this.warehouseRepository = warehouseRepository;
        this.supplierRepository = supplierRepository;
        this.productRepository = productRepository;
        this.passwordEncoder = passwordEncoder;
        this.jdbc = jdbc;
        this.objectMapper = objectMapper;
        this.clock = clock;
    }

    @Override
    @Transactional
    public void run(ApplicationArguments args) throws IOException {
        if (!properties.demo().seedData() || userRepository.count() > 0) {
            return;
        }
        long started = System.currentTimeMillis();
        Instant now = clock.instant();

        List<SeedData.WarehouseSeed> warehouseSeeds = read("warehouses.json", new TypeReference<>() { });
        List<SeedData.SupplierSeed> supplierSeeds = read("suppliers.json", new TypeReference<>() { });
        List<SeedData.ProductSeed> productSeeds = read("products.json", new TypeReference<>() { });
        List<SeedData.UserSeed> userSeeds = read("users.json", new TypeReference<>() { });

        Instant createdAt = now.minusSeconds(HistorySimulator.DAYS * 86_400L + 86_400L);
        Map<String, Warehouse> warehouses = new HashMap<>();
        Map<String, Double> demandFactor = new HashMap<>();
        for (SeedData.WarehouseSeed w : warehouseSeeds) {
            warehouses.put(w.code(), warehouseRepository.save(new Warehouse(w.code(), w.name(), w.address(), createdAt)));
            demandFactor.put(w.code(), w.demandFactor());
        }
        Map<String, Supplier> suppliers = new HashMap<>();
        for (SeedData.SupplierSeed s : supplierSeeds) {
            suppliers.put(s.name(), supplierRepository.save(
                    new Supplier(s.name(), s.contactEmail(), s.phone(), s.leadTimeDays(), createdAt)));
        }
        Map<String, Product> products = new HashMap<>();
        for (SeedData.ProductSeed p : productSeeds) {
            products.put(p.sku(), productRepository.save(new Product(p.sku(), p.name(), p.category(), p.unit(),
                    p.unitCost(), p.description(), suppliers.get(p.supplier()), createdAt)));
        }
        List<User> users = new ArrayList<>();
        for (SeedData.UserSeed u : userSeeds) {
            User user = new User(u.email(), passwordEncoder.encode(u.password()), u.fullName(), Role.valueOf(u.role()),
                    createdAt);
            user.assignWarehouses(u.warehouses().stream().map(warehouses::get).toList());
            users.add(userRepository.save(user));
        }
        userRepository.flush();

        HistorySimulator simulator = new HistorySimulator(
                profiles(productSeeds, products, warehouses, demandFactor), simulatorUsers(users), now);
        simulator.run();
        persist(simulator, products, suppliers, warehouses);

        log.info("Demo data seeded in {} ms: {} warehouses, {} products, {} users, {} movements, {} purchase orders, "
                        + "{} transfers", System.currentTimeMillis() - started, warehouses.size(), products.size(),
                users.size(), simulator.movements.size(), simulator.orders.size(), simulator.transfers.size());
    }

    private List<HistorySimulator.PairProfile> profiles(List<SeedData.ProductSeed> seeds, Map<String, Product> products,
                                                        Map<String, Warehouse> warehouses,
                                                        Map<String, Double> demandFactor) {
        List<HistorySimulator.PairProfile> profiles = new ArrayList<>();
        for (SeedData.ProductSeed seed : seeds) {
            Product product = products.get(seed.sku());
            Supplier supplier = product.getSupplier();
            for (String code : seed.demand().warehouses()) {
                double mean = seed.demand().baseDailyUsage() * demandFactor.get(code);
                int lead = supplier.getLeadTimeDays();
                // Policy sized for the product's *original* demand, so rising products drift into risk.
                int reorderPoint = Math.max(2, (int) Math.ceil(mean * (lead + 2)));
                int orderUpTo = reorderPoint + Math.max(10, (int) Math.ceil(mean * 30));
                profiles.add(new HistorySimulator.PairProfile(
                        new HistorySimulator.Pair(product.getId(), warehouses.get(code).getId()), supplier.getId(),
                        lead, mean, seed.demand().variability(), seed.demand().trend(), reorderPoint, orderUpTo));
            }
        }
        return profiles;
    }

    private static HistorySimulator.Users simulatorUsers(List<User> users) {
        Map<Long, Long> clerks = new HashMap<>();
        Map<Long, Long> managers = new HashMap<>();
        long adminId = users.getFirst().getId();
        for (User u : users) {
            switch (u.getRole()) {
                case ADMIN -> adminId = u.getId();
                case MANAGER -> u.getWarehouses().forEach(w -> managers.putIfAbsent(w.getId(), u.getId()));
                case CLERK -> u.getWarehouses().forEach(w -> clerks.putIfAbsent(w.getId(), u.getId()));
            }
        }
        return new HistorySimulator.Users(clerks, managers, adminId);
    }

    /** Allocates real ids for documents, then bulk-inserts documents, ledger and stock levels. */
    private void persist(HistorySimulator sim, Map<String, Product> products, Map<String, Supplier> suppliers,
                         Map<String, Warehouse> warehouses) {
        List<Long> orderIds = allocate("purchase_orders_id_seq", sim.orders.size());
        List<Long> transferIds = allocate("transfers_id_seq", sim.transfers.size());
        Map<Long, String> supplierNames = suppliers.values().stream()
                .collect(Collectors.toMap(Supplier::getId, Supplier::getName));
        Map<Long, String> warehouseCodes = warehouses.values().stream()
                .collect(Collectors.toMap(Warehouse::getId, Warehouse::getCode));

        List<Object[]> orderRows = new ArrayList<>();
        List<Object[]> orderLineRows = new ArrayList<>();
        Map<Long, Product> productsById = products.values().stream()
                .collect(Collectors.toMap(Product::getId, Function.identity()));
        for (int i = 0; i < sim.orders.size(); i++) {
            HistorySimulator.Order o = sim.orders.get(i);
            orderRows.add(new Object[]{orderIds.get(i), o.supplierId, o.warehouseId, o.status, Date.valueOf(o.expectedDate),
                    o.note, o.createdBy, ts(o.createdAt), "CANCELLED".equals(o.status) ? null : ts(o.createdAt),
                    ts(o.closedAt)});
            for (Map.Entry<Long, int[]> line : o.lines.entrySet()) {
                orderLineRows.add(new Object[]{orderIds.get(i), line.getKey(), line.getValue()[0], line.getValue()[1],
                        productsById.get(line.getKey()).getUnitCost()});
            }
        }
        batch("""
                INSERT INTO purchase_orders (id, supplier_id, warehouse_id, status, expected_date, note, created_by,
                    created_at, ordered_at, closed_at, version) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0)
                """, orderRows);
        batch("""
                INSERT INTO purchase_order_lines (purchase_order_id, product_id, quantity, received_quantity, unit_cost)
                VALUES (?, ?, ?, ?, ?)
                """, orderLineRows);

        List<Object[]> transferRows = new ArrayList<>();
        List<Object[]> transferLineRows = new ArrayList<>();
        for (int i = 0; i < sim.transfers.size(); i++) {
            HistorySimulator.Transfer t = sim.transfers.get(i);
            boolean dispatched = t.dispatchedAt != null;
            boolean received = t.receivedAt != null;
            transferRows.add(new Object[]{transferIds.get(i), t.sourceId, t.destinationId, t.status, t.note, t.createdBy,
                    ts(t.createdAt), dispatched ? t.createdBy : null, ts(t.dispatchedAt),
                    received ? t.createdBy : null, ts(t.receivedAt)});
            for (Map.Entry<Long, int[]> line : t.lines.entrySet()) {
                transferLineRows.add(new Object[]{transferIds.get(i), line.getKey(), line.getValue()[0],
                        line.getValue()[1] < 0 ? null : line.getValue()[1]});
            }
        }
        batch("""
                INSERT INTO transfers (id, source_warehouse_id, destination_warehouse_id, status, note, created_by,
                    created_at, dispatched_by, dispatched_at, received_by, received_at, version)
                VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 0)
                """, transferRows);
        batch("INSERT INTO transfer_lines (transfer_id, product_id, quantity, received_quantity) VALUES (?, ?, ?, ?)",
                transferLineRows);

        List<HistorySimulator.Movement> movements = new ArrayList<>(sim.movements);
        movements.sort(Comparator.comparing(HistorySimulator.Movement::at));
        List<Object[]> movementRows = new ArrayList<>(movements.size());
        for (HistorySimulator.Movement m : movements) {
            Long referenceId = null;
            String reason = m.reason();
            if ("PURCHASE_ORDER".equals(m.referenceType())) {
                HistorySimulator.Order o = sim.orders.get(m.docRef());
                referenceId = orderIds.get(m.docRef());
                reason = "PO #" + referenceId + " from " + supplierNames.get(o.supplierId);
            } else if ("TRANSFER".equals(m.referenceType())) {
                HistorySimulator.Transfer t = sim.transfers.get(m.docRef());
                referenceId = transferIds.get(m.docRef());
                reason = "TRANSFER_OUT".equals(m.type())
                        ? "Transfer #" + referenceId + " to " + warehouseCodes.get(t.destinationId)
                        : "Transfer #" + referenceId + " from " + warehouseCodes.get(t.sourceId);
            }
            movementRows.add(new Object[]{m.productId(), m.warehouseId(), m.type(), m.quantity(), m.balanceAfter(),
                    reason, m.referenceType(), referenceId, m.userId(), ts(m.at())});
        }
        batch("""
                INSERT INTO stock_movements (product_id, warehouse_id, type, quantity, balance_after, reason,
                    reference_type, reference_id, user_id, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, movementRows);

        List<Object[]> levelRows = new ArrayList<>();
        Timestamp now = ts(clock.instant());
        sim.onHand.forEach((pair, qty) -> levelRows.add(new Object[]{pair.productId(), pair.warehouseId(), qty,
                sim.reserved.getOrDefault(pair, 0), sim.reorderPoints.getOrDefault(pair, 0), now}));
        batch("""
                INSERT INTO stock_levels (product_id, warehouse_id, on_hand, reserved, reorder_point, version, updated_at)
                VALUES (?, ?, ?, ?, ?, 0, ?)
                """, levelRows);
    }

    private List<Long> allocate(String sequence, int count) {
        if (count == 0) {
            return List.of();
        }
        return jdbc.queryForList("SELECT nextval('" + sequence + "') FROM generate_series(1, ?)", Long.class, count);
    }

    private void batch(String sql, List<Object[]> rows) {
        for (int from = 0; from < rows.size(); from += BATCH) {
            jdbc.batchUpdate(sql, rows.subList(from, Math.min(from + BATCH, rows.size())));
        }
    }

    private <T> T read(String file, TypeReference<T> type) throws IOException {
        try (InputStream in = new ClassPathResource("seed/" + file).getInputStream()) {
            return objectMapper.readValue(in, type);
        }
    }

    private static Timestamp ts(Instant instant) {
        return instant == null ? null : Timestamp.from(instant);
    }
}
